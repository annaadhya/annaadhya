/**
 * Hostinger NestJS preset entry emitter.
 *
 * Hostinger's Node.js deployment starts NestJS apps from the OUTPUT DIRECTORY
 * with the entry file resolved relative to it (docs.hostinger.com/node.js/
 * build-settings: "For NestJS with output directory `dist`, enter `main.js`").
 * Our real bootstrap is src/boot.ts -> dist/src/boot.js, so this script emits
 * CJS launcher shims so EVERY plausible entry value boots the same bootstrap:
 *
 *   dist/main.js      (Hostinger NestJS default; panel "Entry file: main.js")
 *   dist/boot.js      (entry variant without the src/ prefix)
 *   dist/src/main.js  (entry variant with the src/ prefix, main filename)
 *   dist/src/boot.js  (the real compiled bootstrap, emitted by tsc)
 *
 * boot.js is self-executing: it calls boot() at module top level and binds
 * process.env.PORT (with a boot-error reporter that serves the exact failure
 * over HTTP on boot failure), so requiring it from any launcher starts the
 * full API. All four candidates are kept byte-equivalent in behavior.
 *
 * Runs after tsc via the package build script. Vercel is unaffected: its
 * entrypoint is src/main.ts (the .generated-main.js shim), not the dist
 * launchers, and the extra files change nothing for the bundler.
 */
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dist = join(dirname(fileURLToPath(import.meta.url)), "..", "dist");
const boot = join(dist, "src", "boot.js");

if (!existsSync(boot)) {
  console.error("[emit-dist-main] dist/src/boot.js missing - run tsc first");
  process.exit(1);
}

mkdirSync(dist, { recursive: true });

/**
 * Launcher body. Kept to a single bare require: module resolution inside Node
 * is file-relative (not cwd-relative), so each shim only needs the correct
 * relative path to the compiled bootstrap. No fallback gymnastics - if the
 * file next to the shim is missing, the artifact was truncated in transit and
 * no entry value could have worked anyway.
 */
const launcher = (rel) =>
  "// Auto-generated by scripts/emit-dist-main.mjs - do not edit.\n" +
  "// Hostinger NestJS preset starts the app from an entry file inside the\n" +
  "// output directory; boot.js self-starts (boot().catch) and binds\n" +
  "// process.env.PORT. All entry candidates launch the same bootstrap.\n" +
  `require("${rel}");\n`;

writeFileSync(join(dist, "main.js"), launcher("./src/boot.js"));
writeFileSync(join(dist, "boot.js"), launcher("./src/boot.js"));
mkdirSync(join(dist, "src"), { recursive: true });
writeFileSync(join(dist, "src", "main.js"), launcher("./boot.js"));

console.log(
  "[emit-dist-main] wrote dist/main.js, dist/boot.js, dist/src/main.js -> dist/src/boot.js",
);
