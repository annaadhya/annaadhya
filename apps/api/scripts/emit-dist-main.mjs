/**
 * Hostinger NestJS preset entry emitter.
 *
 * Hostinger's Node.js deployment auto-detects "Application type: NestJS" and
 * documents the entry file as relative to the OUTPUT DIRECTORY with the
 * conventional value `main.js` (docs.hostinger.com/node.js/build-settings:
 * "For NestJS with output directory `dist`, enter `main.js`"). Our real
 * bootstrap is src/boot.ts -> dist/src/boot.js, which does not match that
 * convention, so we emit a one-line launcher at dist/main.js.
 *
 * boot.js is self-executing: it calls boot() at module top level and binds
 * process.env.PORT (with a boot-error reporter that serves the exact failure
 * over HTTP on boot failure), so requiring it from main.js starts the full API.
 *
 * Runs after tsc via the package build script. Vercel is unaffected: its
 * entrypoint is src/main.ts (the .generated-main.js shim), not dist/main.js,
 * and the extra file changes nothing for the bundler.
 */
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dist = join(dirname(fileURLToPath(import.meta.url)), "..", "dist");
const boot = join(dist, "src", "boot.js");

if (!existsSync(boot)) {
  console.error("[emit-dist-main] dist/src/boot.js missing - run tsc first");
  process.exit(1);
}

mkdirSync(dist, { recursive: true });
writeFileSync(
  join(dist, "main.js"),
  "// Auto-generated by scripts/emit-dist-main.mjs - do not edit.\n" +
    "// Hostinger NestJS preset starts the app from the conventional main.js\n" +
    "// inside the output directory; boot.js self-starts (boot().catch) and\n" +
    "// binds process.env.PORT.\n" +
    'require("./src/boot.js");\n',
);
console.log("[emit-dist-main] wrote dist/main.js -> src/boot.js");
